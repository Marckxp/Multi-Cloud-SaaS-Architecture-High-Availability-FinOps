#!/usr/bin/env node
// Writes the showcase free text (README sections, docs/roadmap.md, finops/*.md) with ONE call
// to a model, using only facts/ as input. No agent loop: the model only returns text, and the script
// writes the target file only after the verifiers approve it.
//
//   node tools/write-text.mjs --target docs/roadmap.md --task "Update the roadmap conditions."
//
// The provider is any endpoint compatible with the OpenAI chat API; switching provider means switching variables:
//   WRITER_URL    endpoint base, without /chat/completions
//                 Gemini API:            https://generativelanguage.googleapis.com/v1beta/openai
//                 Cloudflare Workers AI: https://api.cloudflare.com/client/v4/accounts/<ACCOUNT_ID>/ai/v1
//                 LM Studio (local):     http://localhost:1234/v1
//   WRITER_MODEL  model name at the provider
//   WRITER_KEY    API key (any value on LM Studio). Environment variable only: never written or printed.
//
// Exit codes: 0 accepted (written, or no change), 1 text rejected (nothing is written),
// 2 usage or configuration (includes a missing key), 3 provider failure.
//
// Acceptance: the candidate goes into a temporary copy of the repository and passes
// check-leaks (files and history), rules R1 to R6 (review-text), generate-readme --check,
// generate-adrs --check (the extended R7 rule: docs/adr/ is generated) and verify-facts.

import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, posix } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const defaultRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const TIMEOUT_MS = 300_000;
const TARGETS = /^(README\.md|docs\/roadmap\.md|finops\/[^/]+\.md)$/;

export class ExitError extends Error {
  constructor(code, message) {
    super(message);
    this.code = code;
  }
}

export function readConfig(env) {
  const missing = ["WRITER_URL", "WRITER_MODEL", "WRITER_KEY"].filter((n) => !env[n]);
  if (missing.length) throw new ExitError(2, `Missing environment variables: ${missing.join(", ")}. See the header of write-text.mjs.`);
  let url;
  try {
    url = new URL(env.WRITER_URL);
  } catch {
    throw new ExitError(2, "WRITER_URL is not a valid URL.");
  }
  const local = ["localhost", "127.0.0.1", "[::1]"].includes(url.hostname);
  if (url.protocol !== "https:" && !(url.protocol === "http:" && local))
    throw new ExitError(2, "WRITER_URL must be https (http only for localhost), so the key never travels in the clear.");
  return { url: url.href.replace(/\/+$/, ""), host: url.hostname, model: env.WRITER_MODEL, key: env.WRITER_KEY };
}

// Builds the request without sending it: this is what the test checks.
export function buildRequest(config, messages) {
  return {
    endpoint: `${config.url}/chat/completions`,
    options: {
      method: "POST",
      headers: { "Content-Type": "application/json", Authorization: `Bearer ${config.key}` },
      body: JSON.stringify({ model: config.model, messages, temperature: 0.2 }),
    },
  };
}

// The only function that uses the network. The test passes a fake fetch.
export async function callProvider(config, messages, fetchFn = globalThis.fetch) {
  const { endpoint, options } = buildRequest(config, messages);
  const hide = (t) => String(t).replaceAll(config.key, "***");
  let response;
  try {
    response = await fetchFn(endpoint, { ...options, signal: AbortSignal.timeout(TIMEOUT_MS) });
  } catch (error) {
    throw new ExitError(3, `Network failure with ${config.host}: ${hide(error.message)}`);
  }
  const body = await response.text();
  if (!response.ok) throw new ExitError(3, `${config.host} responded ${response.status}: ${hide(body).slice(0, 200)}`);
  let text;
  try {
    text = JSON.parse(body).choices?.[0]?.message?.content;
  } catch {
    text = null;
  }
  if (typeof text !== "string" || !text.trim()) throw new ExitError(3, `${config.host} responded without text in choices[0].message.content.`);
  return text;
}

// Removes the code fence that models tend to wrap around the whole file.
export function cleanResponse(text) {
  const lines = text.trim().replaceAll("\r\n", "\n").split("\n");
  if (lines.length > 2 && lines[0].startsWith("```") && lines.at(-1).trim() === "```") {
    lines.pop();
    lines.shift();
  }
  return lines.join("\n").trim() + "\n";
}

export function validateTarget(target) {
  const clean = posix.normalize(String(target ?? ""));
  if (!TARGETS.test(clean)) throw new ExitError(2, "--target must be README.md, docs/roadmap.md or finops/<file>.md (docs/adr/ is generated by generate-adrs.mjs).");
  return clean;
}

const SYSTEM = [
  "You write the free text of a public showcase of a SaaS architecture, in English.",
  "The only source of facts is the content of facts/ that the user sends. Use no other knowledge.",
  "Rules: short sentences, no marketing; no number, service, state or name that is not in the facts;",
  "no capacity claim (RPS, SLA, concurrent users); nothing from the product's business domain;",
  "no account identifier, IP, email, provider hostname or user path; use <PLACEHOLDER> for account values.",
  "Never change what is between <!-- generated:X:start --> and <!-- generated:X:end -->; keep those markers.",
  "Reply ONLY with the complete new content of the target file, with no code fences and no comments of your own.",
].join(" ");

function readFacts(root) {
  const parts = [`### facts/state.json\n${readFileSync(join(root, "facts", "state.json"), "utf8")}`];
  const folder = join(root, "facts", "decisions");
  for (const n of readdirSync(folder).filter((x) => x.endsWith(".md")).sort())
    parts.push(`### facts/decisions/${n}\n${readFileSync(join(folder, n), "utf8")}`);
  return parts.join("\n\n");
}

export function buildMessages(root, target, task) {
  const current = readFileSync(join(root, target), "utf8");
  const user = `Task: ${task}\n\nTarget file: ${target}\n\n## Facts\n\n${readFacts(root)}\n\n## Current content of ${target}\n\n${current}`;
  return [{ role: "system", content: SYSTEM }, { role: "user", content: user }];
}

// NOSONAR(S4036): git comes from the PATH of the runner or the maintainer's machine; an absolute path would break between Linux and Windows.
const git = (cwd, ...a) => execFileSync("git", ["-c", "user.name=writer", "-c", "user.email=writer@example.org", "-c", "commit.gpgsign=false", ...a], { cwd, encoding: "utf8" }); // NOSONAR

function run(cwd, env, script, ...a) {
  try {
    const output = execFileSync(process.execPath, [join("tools", script), ...a], { cwd, env, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
    return { ok: true, output };
  } catch (error) {
    return { ok: false, output: `${error.stdout ?? ""}${error.stderr ?? ""}`.trim(), code: error.status };
  }
}

// Puts the candidate in a temporary copy (current disk state as the base) and runs the verifiers.
export function evaluate(root, target, candidate, env = process.env) {
  const tmp = mkdtempSync(join(tmpdir(), "showcase-writer-"));
  const reasons = [];
  try {
    const files = git(root, "ls-files", "-co", "--exclude-standard").split("\n").filter(Boolean);
    for (const f of files) {
      mkdirSync(dirname(join(tmp, f)), { recursive: true });
      copyFileSync(join(root, f), join(tmp, f));
    }
    git(tmp, "init", "-q");
    git(tmp, "add", "--", ...files);
    git(tmp, "commit", "-q", "-m", "base");
    const base = git(tmp, "rev-parse", "HEAD").trim();
    mkdirSync(dirname(join(tmp, target)), { recursive: true });
    writeFileSync(join(tmp, target), candidate);
    git(tmp, "add", "--", target);
    git(tmp, "commit", "-q", "-m", "free text from the facts");
    const checks = [
      ["leak check", "check-leaks.mjs", "--require-list", "--range", `${base}..HEAD`],
      ["rules R1 to R6", "review-text.mjs", "--base", base, "--head", "HEAD"],
      ["README up to date", "generate-readme.mjs", "--check"],
      ["ADRs up to date (extended R7)", "generate-adrs.mjs", "--check"],
      ["facts valid", "verify-facts.mjs"],
    ];
    for (const [name, script, ...a] of checks) {
      const r = run(tmp, env, script, ...a);
      if (!r.ok) reasons.push(`${name}:\n${r.output}`);
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
  return { ok: reasons.length === 0, reasons };
}

// The whole flow; `call` is the network function (replaced in tests).
export async function write({ root = defaultRoot, target, task, env = process.env, call = callProvider, log = console.log }) {
  if (!task?.trim()) throw new ExitError(2, "Missing --task.");
  const path = validateTarget(target);
  const config = readConfig(env);
  const raw = await call(config, buildMessages(root, path, task));
  const candidate = cleanResponse(raw);
  const current = readFileSync(join(root, path), "utf8").replaceAll("\r\n", "\n");
  if (candidate === current) {
    log(`${path}: no change.`);
    return 0;
  }
  const verdict = evaluate(root, path, candidate, env);
  if (!verdict.ok) {
    for (const m of verdict.reasons) console.error(`REJECTED in ${m}`);
    console.error(`Text rejected: ${path} was not changed.`);
    return 1;
  }
  writeFileSync(join(root, path), candidate);
  log(`${path}: text accepted by the verifiers and written.`);
  return 0;
}

function readArgs(argv) {
  const pick = (n) => {
    const i = argv.indexOf(n);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  return { target: pick("--target"), task: pick("--task") };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    process.exitCode = await write(readArgs(process.argv.slice(2)));
  } catch (error) {
    if (!(error instanceof ExitError)) throw error;
    console.error(`ERROR: ${error.message}`);
    process.exitCode = error.code;
  }
}
